#!/usr/bin/env bash
# Concatenates every migration plus the seed into ONE file you can paste into the Supabase SQL editor.
# Output: supabase/setup-all.sql   (never includes local-stub.sql)
set -euo pipefail
cd "$(dirname "$0")/.."
OUT=supabase/setup-all.sql
{
  echo "-- Pemart: full Supabase setup (migrations + demo seed). Generated by scripts/build-supabase-setup.sh. Run once on an EMPTY project."
  for f in supabase/migrations/*.sql; do echo; echo "-- ================= $f ================="; cat "$f"; done
  echo; echo "-- ================= supabase/seed.sql ================="; cat supabase/seed.sql
} > "$OUT"
echo "Wrote $OUT ($(wc -c < "$OUT") bytes)"

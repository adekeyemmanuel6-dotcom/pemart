#!/usr/bin/env bash
# Concatenate supabase/seed/*.sql (in order) into supabase/seed.sql
set -euo pipefail
cd "$(dirname "$0")/.."
{ echo "-- GENERATED by scripts/build-seed.sh from supabase/seed/*.sql. Edit the parts, not this file."
  for f in supabase/seed/*.sql; do echo; echo "-- ===== $(basename "$f") ====="; cat "$f"; done; } > supabase/seed.sql
echo "Built supabase/seed.sql"
